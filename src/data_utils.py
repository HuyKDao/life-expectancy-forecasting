import pandas as pd

def clean_health_data(df):
    """
    Clean the World Bank Health Nutrition Population dataset.
    """

    df_clean = df.copy()

    # Remove unnamed columns
    unnamed_cols = [col for col in df_clean.columns if col.startswith("Unnamed")]
    df_clean = df_clean.drop(columns=unnamed_cols, errors="ignore")

    # Standardize column names
    df_clean.columns = df_clean.columns.str.strip()

    # Identify year columns
    year_cols = sorted([col for col in df_clean.columns if col.isdigit()], key=int)

    # Convert year columns to numeric
    df_clean[year_cols] = df_clean[year_cols].apply(pd.to_numeric, errors="coerce")

    # Remove duplicates
    df_clean = df_clean.drop_duplicates()

    # Drop rows where all years are missing
    df_clean = df_clean.dropna(subset=year_cols, how="all")

    return df_clean, year_cols